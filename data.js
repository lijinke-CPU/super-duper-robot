/* 根据条目 id 稳定取一张封面（同类内尽量错开） */
function coverOf(it) {
  var arr = COVERS[it.cat];
  if (!arr) return IMG[it.cat];
  var h = 0;
  for (var i = 0; i < it.id.length; i++) h = (h * 31 + it.id.charCodeAt(i)) >>> 0;
  return arr[h % arr.length];
}

