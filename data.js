function searchItems(query) {
  const q = (query || "").toLowerCase().trim();
  if (!q) return [];
  let rules = [];
  Object.keys(KEYWORD_MAP).forEach(k => { if (q.includes(k)) rules = rules.concat(KEYWORD_MAP[k]); });
  let result;
  if (rules.length) {
    result = DB.filter(function (it) {
      return rules.some(function (r) {
        if (typeof r === "string") return it.cat === r;
        return it.cat === r.cat && subsOf(it).indexOf(r.sub) !== -1;
      });
    });
    // 标题/作者直接命中者优先
    const direct = DB.filter(it => (it.title + it.author + it.tags.join("")).toLowerCase().includes(q));
    if (direct.length) result = direct.concat(result.filter(it => !direct.includes(it)));
  } else {
    result = DB.filter(it => (it.title + it.author + it.tags.join("") + it.intro + CAT_NAME[it.cat]).toLowerCase().includes(q));
  }
  return result.slice(0, 30);
}
